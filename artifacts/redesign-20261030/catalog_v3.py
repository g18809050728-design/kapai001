"""Hand-authored design proposal; never imported by the game."""
from collections import Counter

OWNERS = {'C': '公共校园池', 'P01': '林序', 'P02': '许知微', 'P03': '沈见章', 'P04': '唐以宁'}
CARDS = []


def group(owner, title, rows):
    start = sum(c['owner'] == owner for c in CARDS)
    lines = rows.strip().splitlines()
    assert len(lines) == (12 if owner == 'C' else 10), (owner, title, len(lines))
    for offset, line in enumerate(lines, 1):
        name, cost, kind, base, upgraded, tags = [x.strip() for x in line.split('|')]
        costs = [int(x) for x in cost.split('/')]
        number = start + offset
        rarity = ('普通' if offset <= 5 else '进阶') if offset < 10 else '稀有'
        if owner != 'C' and number == 9:
            rarity = '稀有'
        if owner == 'C':
            rarity = '基础' if offset <= 2 else ('进阶' if offset in (6, 8) else '普通')
        CARDS.append(dict(id=f'R3-{owner}-{number:02}', owner=owner, character=OWNERS[owner],
                          name=name, name_key=f'R3-{owner}-{number:02}', group=title,
                          cost=costs[0], upgraded_cost=costs[-1], type=kind, rarity=rarity,
                          base=base, upgraded=upgraded, tags=tags.split('、'), permanent=True,
                          exam_condition='', exam='', exam_upgraded='', chapter='', chapter_upgraded=''))


