def edit(name, replacements=(), transform=None):
    p = ROOT / name
    before = p.read_text(encoding='utf-8')
    text = before
    for old, new in replacements:
        if old not in text:
            raise ValueError(f'Missing expected text in {name}: {old[:90]}')
        text = text.replace(old, new)
    if transform:
        text = transform(text)
    if text != before:
        p.write_text(text, encoding='utf-8')
        changed.append(name)


