def main():
    design = json.loads((ROOT / "artifacts/redesign-20261030/campus-cards-v3.json").read_text(encoding="utf-8-sig"))
    cards = design["cards"] + design["tokens"]
    subjects = {key: value.splitlines() for key, value in SUBJECTS.items()}
    for key in ["P01", "P02", "P03", "P04"]:
        assert len(subjects[key]) == 40
    counters = {key: 0 for key in subjects}
    asset_file = ROOT / "docs/art/card-art-assets-v3.json"
    assets = json.loads(asset_file.read_text(encoding="utf-8")) if asset_file.exists() else {"assets": []}
    produced = {a["asset_id"]: a for a in assets["assets"]}
    entries = []
    for card in cards:
        cid = card["id"]
        group = "T" if cid.startswith("R3-T") else card["owner"]
        subject = subjects[group][counters[group]]
        counters[group] += 1
        anchor = ANCHORS["P02" if group == "T" else group]
        prompt = STYLE + anchor + "主体场景：" + subject + "。主体占画面中央60%，四周各留10%可裁切空间；关键手势、物件和视线完整，背景简化，顶部与底部不放不可裁切信息。"
        asset = produced.get(cid, {})
        entries.append(dict(card_id=cid, name=card["name"], owner=card["owner"], subject=subject, group=card.get("group", "论文衍生"),
                            image_path="res://assets/cards/v3/" + cid + ".png", prompt=prompt, negative_prompt=NEGATIVE,
                            upgrade_policy="与基础面复用同一插画；升级光效/边框由UI叠加，不另生同名卡", generated=asset.get("generated", False), selected=asset.get("selected", False)))
    assert len(entries) == 174 and len({e["card_id"] for e in entries}) == 174
    out = ROOT / "docs/art/card-art-prompts-v3.json"
    out.parent.mkdir(parents=True, exist_ok=True)
