FONT_NAME = "微软雅黑"
HDR_FILL = PatternFill("solid", fgColor="2F5597")
HDR_FONT = Font(name=FONT_NAME, size=10.5, bold=True, color="FFFFFF")
BODY_FONT = Font(name=FONT_NAME, size=10)
NOTE_FONT = Font(name=FONT_NAME, size=9.5, italic=True, color="808080")
TITLE_FONT = Font(name=FONT_NAME, size=14, bold=True, color="2F5597")
THIN = Side(style="thin", color="BFBFBF")
BORDER = Border(left=THIN, right=THIN, top=THIN, bottom=THIN)
BAND_FILL = PatternFill("solid", fgColor="F2F5FA")


def add_sheet(wb, name, title, headers, rows, widths, notes=None):
    ws = wb.create_sheet(name)
    ws.sheet_view.showGridLines = False
    ncol = max(1, len(headers))

    ws.cell(row=1, column=1, value=title).font = TITLE_FONT
    ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=ncol)
    ws.row_dimensions[1].height = 28

    for c, h in enumerate(headers, start=1):
        cell = ws.cell(row=2, column=c, value=h)
        cell.font = HDR_FONT
        cell.fill = HDR_FILL
        cell.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        cell.border = BORDER
    ws.row_dimensions[2].height = 24

    for r, row in enumerate(rows, start=3):
        for c, v in enumerate(row, start=1):
            cell = ws.cell(row=r, column=c, value=v)
            cell.font = BODY_FONT
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            cell.border = BORDER
            if (r - 3) % 2 == 1:
                cell.fill = BAND_FILL

    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w

    if notes:
        r = len(rows) + 4
        for n in notes:
            cell = ws.cell(row=r, column=1, value=n)
            cell.font = NOTE_FONT
            cell.alignment = Alignment(vertical="top", wrap_text=True)
            ws.merge_cells(start_row=r, start_column=1, end_row=r, end_column=ncol)
            r += 1

    ws.freeze_panes = ws.cell(row=3, column=1)
    ws.auto_filter.ref = "A2:%s%d" % (get_column_letter(ncol), len(rows) + 2)
    return ws


